function _clean(s){ return (s||'').replace(/\s+/g,'').replace(/[：:*]/g,'').trim() }
function _scope(){
  try{ const seg=(location.pathname.split('/')[1]||'').toLowerCase(); return TIPS_SCOPED[seg]||null }catch(e){ return null }
}
const _SEL='.el-button, .el-table th .cell, .el-form-item__label, .el-checkbox__label, .el-radio__label, '+
  '.el-radio-button__inner, .el-tabs__item, .stat-card .l, .el-descriptions__label, .el-statistic__head, '+
  '.el-menu-item, .el-dropdown-menu__item, .el-select-dropdown__item, .el-divider__text, .el-tag, .el-link'
function applyTips(root){
  try{
    root=root||document
    if(!root.querySelectorAll)return
    const sc=_scope()
    root.querySelectorAll(_SEL).forEach(function(el){
      const key=_clean(el.textContent)
      if(!key||key.length>24)return
      if(el.getAttribute('data-tip-key')===key)return   // 文本变化(如 启用↔停用)时重算
      el.setAttribute('data-tip-key',key)
      const tip=(sc&&sc[key])||TIPS[key]; if(!tip)return
      const host=el.closest('.el-button')||el.closest('th')||el
      // 不覆盖手写 title; 自己挂过的(data-tip-host)允许随文本更新
      if(host.getAttribute('title') && !host.getAttribute('data-tip-host'))return
      host.setAttribute('title',tip); host.setAttribute('data-tip-host','1')
    })
  }catch(e){}
}
export function installTips(){
  const run=function(){ applyTips(document) }
  if(document.readyState!=='loading')run(); else document.addEventListener('DOMContentLoaded',run)
  let pend=null
  const mo=new MutationObserver(function(){ if(pend)return; pend=setTimeout(function(){ pend=null; applyTips(document) },300) })
  mo.observe(document.body,{childList:true,subtree:true})
}
